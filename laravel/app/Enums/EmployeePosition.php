<?php

namespace App\Enums;

/**
 * Должность сотрудника внутри компании. Ровно 4 значения — закреплено
 * намеренно (раньше `position` было свободным текстом), чтобы на это
 * поле можно было опираться при выдаче прав доступа в интерфейсе.
 *
 * ВАЖНО: права ниже — это пока только ДОКУМЕНТАЦИЯ (согласованный текст),
 * реальных проверок доступа в коде для них ещё нет. Когда будет
 * реализовываться видимость разделов CRM — ориентируйся на этот список.
 *
 * Матрица прав (согласовано на этапе проектирования):
 *
 * | Должность          | Заказчики | Водители | Заявки | Финансы     | Редактирование |
 * |---------------------|-----------|----------|--------|-------------|----------------|
 * | Director            | +         | +        | +      | +           | +              |
 * | Logist               | +         | +        | +      | −           | + (кроме финансов) |
 * | Accountant           | +         | +        | +      | +           | − (только просмотр) |
 * | Clerk (делопроизв.)  | +         | +        | +      | +           | +              |
 *
 * Отдельно для Logist в будущем планируется собственная статистика
 * (сколько заработано за день/неделю/месяц) — не финансовый раздел
 * компании целиком, а агрегированные показатели по его же заявкам.
 */
enum EmployeePosition: string
{
    case Director = 'director';
    case Logist = 'logist';
    case Accountant = 'accountant';
    case Clerk = 'clerk';

    /**
     * Название для отображения в интерфейсе (директор сам вводит ИНН/данные
     * на русском, поэтому и должности сотрудников показываем по-русски).
     */
    public function label(): string
    {
        return match ($this) {
            self::Director => 'Директор',
            self::Logist => 'Логист',
            self::Accountant => 'Бухгалтер',
            self::Clerk => 'Делопроизводитель',
        };
    }
}
